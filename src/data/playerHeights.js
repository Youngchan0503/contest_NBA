// 신장 피지컬 핏 판정 헬퍼 (target vs candidate)
export function getPhysicalFitAnalysis(target, candidate) {
  if (!target?.height_cm || !candidate?.height_cm) {
    return {
      diffCm: 0,
      status: 'NEUTRAL',
      label: '신장 정보 대기',
      color: '#64748b',
      bgColor: '#f1f5f9',
      borderColor: '#cbd5e1',
      desc: '신장 비교 데이터 없음'
    };
  }

  const diffCm = candidate.height_cm - target.height_cm;

  if (Math.abs(diffCm) <= 2) {
    return {
      diffCm,
      status: 'PERFECT_FIT',
      label: '신장 싱크로 완벽',
      badge: '🎯 신장 일치',
      color: '#059669',
      bgColor: '#ecfdf5',
      borderColor: '#a7f3d0',
      desc: `기존 선수와 키 차이가 ${Math.abs(diffCm)}cm에 불과해 포지션 높이 손실이 전혀 없습니다.`
    };
  }

  if (diffCm > 2) {
    const isBigAdvantage = diffCm >= 7;
    return {
      diffCm,
      status: 'SIZE_UP',
      label: `사이즈 업사이드 (+${diffCm}cm)`,
      badge: isBigAdvantage ? '🚀 장신화 우위' : '📏 높이 보강',
      color: '#0284c7',
      bgColor: '#e0f2fe',
      borderColor: '#bae6fd',
      desc: `기존 대비 +${diffCm}cm 장신화로 앞선 시야 확보 및 수비 컨테스트 범위를 확장합니다.`
    };
  }

  // diffCm < -2
  const isSevereDeficit = diffCm <= -7;
  return {
    diffCm,
    status: isSevereDeficit ? 'SEVERE_DEFICIT' : 'UNDERSIZED',
    label: `언더사이즈 리스크 (${diffCm}cm)`,
    badge: isSevereDeficit ? '⚠️ 신장 격차 주의' : '📉 높이 열세',
    color: isSevereDeficit ? '#e11d48' : '#d97706',
    bgColor: isSevereDeficit ? '#fff1f2' : '#fef3c7',
    borderColor: isSevereDeficit ? '#fecdd3' : '#fde68a',
    desc: isSevereDeficit
      ? `기존 대비 ${Math.abs(diffCm)}cm 낮아 포지션 미스매치 수비 및 리바운드 경합 시 취약점이 발생할 수 있습니다.`
      : `기존 대비 ${Math.abs(diffCm)}cm 낮지만 상대적으로 빠른 스텝과 기동성을 활용한 대인 수비가 요구됩니다.`
  };
}
